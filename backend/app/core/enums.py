from enum import Enum

class IncidentStatus(str, Enum):
    NEW = "NEW"
    ANALYZING = "ANALYZING"
    PRIORITIZED = "PRIORITIZED"
    RECOMMENDED = "RECOMMENDED"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    APPROVED = "APPROVED"
    IN_PROGRESS = "IN_PROGRESS"
    RESOLVED = "RESOLVED"
    VERIFIED = "VERIFIED"
    REJECTED = "REJECTED"
    CANCELLED = "CANCELLED"
    NEEDS_HUMAN_REVIEW = "NEEDS_HUMAN_REVIEW"

class Severity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"

class BlockageSeverity(str, Enum):
    CLEAR = "CLEAR"           # 0%
    PARTIAL = "PARTIAL"       # ~30-50%
    SEVERE = "SEVERE"         # ~60-80%
    COMPLETE = "COMPLETE"     # 100% blocked

class ActionType(str, Enum):
    DISPATCH_SUPER_SUCKER = "DISPATCH_SUPER_SUCKER"
    DEPLOY_DEWATERING_PUMP = "DEPLOY_DEWATERING_PUMP"
    MANUAL_DESILTING_CREW = "MANUAL_DESILTING_CREW"
    INSTALL_BARRIER_REDIRECT = "INSTALL_BARRIER_REDIRECT"
    ISSUE_TRAFFIC_ADVISORY = "ISSUE_TRAFFIC_ADVISORY"
    INSPECT_CULVERT = "INSPECT_CULVERT"
